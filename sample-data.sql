USE student_voice;
INSERT INTO suggestions (title, category, body, status)
SELECT sample.title, sample.category, sample.body, sample.status
FROM (
    SELECT '放課後の図書室で見つけた、小さな楽しみ' AS title, '学校生活' AS category,
           '放課後、いつもより少しだけ長く学校に残って図書室へ行きました。窓際の席に座ると、校庭の音が遠くに聞こえてきます。

普段は選ばない短編集を手に取ってみたら、気づけば一話を読み終えていました。忙しい日でも、十分だけ本を開く時間があると気持ちが切り替わります。

次は友達のおすすめも読んでみたいです。みなさんのお気に入りの一冊は何ですか？' AS body, 'published' AS status
    UNION ALL SELECT '理科の実験で「なぜ？」が増えた日', '授業',
           '今日の理科は、身近な材料を使って水の性質を調べる実験でした。予想をノートに書いてから試してみると、結果が思っていたものと少し違いました。

同じ班の友達と条件を一つずつ変えて確かめるうちに、「失敗した」と思った結果にも理由があると気づきました。

答えを覚えるだけでなく、自分で疑問を持って調べることが実験の面白さなのかもしれません。次の授業も楽しみです。', 'published'
    UNION ALL SELECT 'いつもの給食が、少し特別に感じた理由', '学校生活',
           '今日の給食は、私の好きなカレーでした。配膳を手伝いながら、毎日これだけの人数の食事を準備するのは大変だろうなと思いました。

昼の放送で食材の産地を聞いて、普段何気なく食べているものにも、たくさんの人の仕事がつながっていることを知りました。

食べ終わった後の「ごちそうさま」を、今日はいつもより少し丁寧に言ってみました。', 'published'
    UNION ALL SELECT '文化祭の準備、アイデアが形になるまで', 'その他',
           '文化祭に向けた話し合いが始まりました。最初は意見がばらばらでしたが、付箋に一つずつ書いて並べると、似ているアイデアが見えてきました。

自分だけでは思いつかなかった案に、別の人の工夫が加わって、新しい企画になっていくのが面白かったです。

まだ決めることはたくさんあります。得意なことを持ち寄って、みんなで楽しめる一日にしていきたいです。', 'published'
    UNION ALL SELECT '朝の校庭を歩いて気づいたこと', '設備',
           '少し早く登校した朝、校庭の端を歩いてみました。花壇には小さな花が咲いていて、昨日の雨のしずくが残っていました。

普段は急いで通り過ぎる場所にも、立ち止まると発見があります。校舎の窓に朝日が映る景色も、いつもと違って見えました。

毎日通う学校だからこそ、まだ知らない場所や風景を見つけてみたいと思います。', 'published'
    UNION ALL SELECT 'ノートのまとめ方を変えてみた', '授業',
           'テスト前にノートを見返しても、大切なところがすぐに見つからないことがありました。そこで、授業の最後に「今日わかったこと」を三行で書くようにしました。

短くまとめようとすると、自分が理解できていない部分にも気づきます。その日のうちに質問できるようになったのが、一番よかったことです。

きれいに書くことだけでなく、後から読んだ自分がわかるノートを目指したいです。', 'published'
    UNION ALL SELECT '新しい学期に、挑戦してみたいこと', 'その他',
           '新しい学期の目標を考えました。大きなことを一度に始めるより、毎日少しずつ続けられることに挑戦したいです。

まずは、授業で一回手を挙げること。そして、話したことのないクラスメートにも挨拶すること。小さな目標ですが、自分にとっては大切な一歩です。

学期の終わりにこの記事を読み返したとき、どんな変化があったか振り返るのが楽しみです。', 'published'
    UNION ALL SELECT '体育祭の練習で学んだ、声をかけること', '学校生活',
           'リレーの練習で、バトンがうまくつながらないことがありました。走る速さだけでなく、お互いに声をかけるタイミングも大切だと気づきました。

何度か練習して少しずつ息が合ってきたときは、班のみんなで喜びました。本番でも、最後まで声をかけ合って走りたいです。', 'pending'
    UNION ALL SELECT '雨の日の教室で過ごした昼休み', '学校生活',
           '今日は雨だったので、教室で友達と折り紙をして過ごしました。同じ紙からいろいろな形ができるのが面白かったです。

外で遊べない日にも、小さな楽しみを見つけられました。', 'hidden'
) AS sample
WHERE NOT EXISTS (
    SELECT 1 FROM suggestions AS existing
    WHERE existing.title = sample.title AND existing.body = sample.body
);
